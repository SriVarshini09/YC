import path from "node:path";
import type { Advisory, Fix, LockedCallSite } from "@shapi/core";
import type { ResponseShape } from "@shapi/shapes";
import { Node, Project, ScriptKind, SyntaxKind, type ParameterDeclaration, type SourceFile, type TypeNode } from "ts-morph";
import { findCall } from "./recipe";
import { bodyFromPaths, synthesizeBody } from "./synth";

export interface ContractTestInput {
  callSite: LockedCallSite;
  advisory: Advisory;
  /**
   * The response the code was written against, and the one the provider sends now. Not needed when
   * the advisory has a `fix`: the test is then built from the fix and the fields the code reads.
   */
  before?: ResponseShape;
  after?: ResponseShape;
  /** Current text of the call site's file. */
  sourceText: string;
}

export type ContractTest =
  | { status: "generated"; file: string; content: string; functionName: string }
  | { status: "unsupported"; reason: string };

/** Where generated tests go, relative to the repo root. */
export const CONTRACT_DIR = "test/shapi";

/** Status the stubbed provider answers a retired request with. */
const RETIRED_STATUS = 410;

/**
 * Generate a vitest file that calls the function containing the call site with `fetch` stubbed.
 * Which stub depends on the change:
 * - a request change (the advisory's `fix` has a path, query or header): the provider rejects the
 *   retired request, so the test fails until the code sends the new one and still works;
 * - a response rename (`fix` has fields or enums): the function must return the same result for the
 *   old and the new response;
 * - otherwise the recorded before and after responses: the function must handle both.
 */
export function generateContractTest(input: ContractTestInput): ContractTest {
  const { callSite, advisory, before, after } = input;
  const fix = advisory.fix;
  if (callSite.kind !== "http" || callSite.client !== "fetch") {
    return { status: "unsupported", reason: `contract tests support global fetch call sites; this one uses ${callSite.client}` };
  }

  const project = new Project({ useInMemoryFileSystem: true, skipFileDependencyResolution: true, compilerOptions: { allowJs: true } });
  const sf = project.createSourceFile(`/${callSite.file}`, input.sourceText, {
    scriptKind: /\.(c|m)?jsx?$/.test(callSite.file) ? ScriptKind.JS : ScriptKind.TS,
  });
  const call = findCall(sf, callSite);
  if (!call) return { status: "unsupported", reason: `no call at ${callSite.file}:${callSite.line}:${callSite.column}` };

  const fn = exportedFunction(call);
  if (!fn) return { status: "unsupported", reason: "the call site is not inside an exported function" };

  const file = `${CONTRACT_DIR}/${advisory.id}.test.ts`;
  const importPath = toImport(path.posix.relative(path.posix.dirname(file), callSite.file));
  const args = fn.params.map((p) => argument(p, sf)).join(", ");
  const header = `// Generated by SHAPI for advisory ${advisory.id}: ${advisory.title}
// Call site: ${callSite.file}:${callSite.line} (${callSite.method} ${callSite.endpoint})`;

  if (fix && (fix.path || fix.query || fix.header)) {
    const content = requestTest({ header, fn: fn.name, importPath, args, advisory, fix, body: renamePair(callSite, fix).after });
    return { status: "generated", file, content, functionName: fn.name };
  }
  if (fix && (fix.fields || fix.enums)) {
    const content = sameResultTest({ header, fn: fn.name, importPath, args, advisory, ...renamePair(callSite, fix) });
    return { status: "generated", file, content, functionName: fn.name };
  }
  if (!before || !after) return { status: "unsupported", reason: "no before/after responses for this endpoint, and the advisory has no fix to build a test from" };

  let responses: string;
  try {
    responses = [response(`before (${before.status})`, before), response(`after (${after.status})`, after)].join(",\n");
  } catch (err) {
    return { status: "unsupported", reason: err instanceof Error ? err.message : String(err) };
  }

  const content = `// Generated by SHAPI for advisory ${advisory.id}: ${advisory.title}
// Call site: ${callSite.file}:${callSite.line} (${callSite.method} ${callSite.endpoint})
// Calls ${fn.name}() with fetch returning the response the code was written for and the one
// ${advisory.provider} sends now. It fails while the code accepts only the old response.
import { afterEach, describe, expect, it, vi } from "vitest";
import { ${fn.name} } from "${importPath}";

const responses = [
${responses},
];

describe("SHAPI contract: ${advisory.id}", () => {
  afterEach(() => {
    vi.unstubAllGlobals();
  });

  for (const r of responses) {
    it(\`${fn.name} handles the \${r.name} response\`, async () => {
      const fetchMock = vi.fn(async () => new Response(r.body === null ? null : JSON.stringify(r.body), { status: r.status, headers: r.headers }));
      vi.stubGlobal("fetch", fetchMock);
      await ${fn.name}(${args});
      expect(fetchMock).toHaveBeenCalled();
    });
  }
});
`;
  return { status: "generated", file, content, functionName: fn.name };
}

interface TestParts {
  header: string;
  fn: string;
  importPath: string;
  args: string;
  advisory: Advisory;
}

/** The provider answers the retired request with 410 and anything else with a body holding the fields the code reads. */
function requestTest(p: TestParts & { fix: Fix; body: unknown }): string {
  const checks: string[] = [];
  if (p.fix.path) checks.push(`url.href.includes(${JSON.stringify(p.fix.path.from)})`);
  if (p.fix.query) {
    const name = JSON.stringify(p.fix.query.name);
    const below = p.advisory.trigger.query?.find((q) => q.name === p.fix.query!.name)?.below;
    checks.push(
      below === undefined
        ? `(url.searchParams.has(${name}) && url.searchParams.get(${name}) !== ${JSON.stringify(p.fix.query.value)})`
        : `(url.searchParams.has(${name}) && Number(url.searchParams.get(${name})) < ${below})`,
    );
  }
  if (p.fix.header) {
    const name = JSON.stringify(p.fix.header.name);
    checks.push(`(headers.has(${name}) && headers.get(${name}) !== ${JSON.stringify(p.fix.header.value)})`);
  }
  return `${p.header}
// The provider no longer accepts the old request: this stub answers it with ${RETIRED_STATUS}, and answers
// anything else with a body holding the fields the code reads. The test fails until ${p.fn}()
// sends the new request (${describeFix(p.fix)}) and still works.
import { afterEach, describe, expect, it, vi } from "vitest";
import { ${p.fn} } from "${p.importPath}";

const body = ${JSON.stringify(p.body)};

function retired(input: RequestInfo | URL, init?: RequestInit): boolean {
  const url = new URL(typeof input === "string" ? input : input instanceof URL ? input.href : input.url, "https://shapi.invalid");
  const headers = new Headers(init?.headers ?? (input instanceof Request ? input.headers : undefined));
  return ${checks.join(" || ")};
}

describe("SHAPI contract: ${p.advisory.id}", () => {
  afterEach(() => {
    vi.unstubAllGlobals();
  });

  it("${p.fn} sends the new request and handles the response", async () => {
    const sent: boolean[] = [];
    const fetchMock = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
      const old = retired(input, init);
      sent.push(old);
      return old
        ? new Response(JSON.stringify({ error: "retired request (SHAPI contract test)" }), { status: ${RETIRED_STATUS}, headers: { "content-type": "application/json" } })
        : new Response(JSON.stringify(body), { status: 200, headers: { "content-type": "application/json" } });
    });
    vi.stubGlobal("fetch", fetchMock);
    await ${p.fn}(${p.args});
    expect(sent.length).toBeGreaterThan(0);
    expect(sent).not.toContain(true);
  });
});
`;
}

/** The function must return the same result whether the provider uses the old or the new field names and values. */
function sameResultTest(p: TestParts & { before: unknown; after: unknown }): string {
  return `${p.header}
// The provider renamed fields or enum values. This test calls ${p.fn}() once with the old response and
// once with the new one, and expects the same result: it fails while the code only reads the old names.
import { afterEach, describe, expect, it, vi } from "vitest";
import { ${p.fn} } from "${p.importPath}";

const responses = [
  { name: "old", body: ${JSON.stringify(p.before)} },
  { name: "new", body: ${JSON.stringify(p.after)} },
];

describe("SHAPI contract: ${p.advisory.id}", () => {
  afterEach(() => {
    vi.unstubAllGlobals();
  });

  it("${p.fn} returns the same result for the old and the new response", async () => {
    const results: unknown[] = [];
    for (const r of responses) {
      vi.stubGlobal("fetch", vi.fn(async () => new Response(JSON.stringify(r.body), { status: 200, headers: { "content-type": "application/json" } })));
      results.push(await ${p.fn}(${p.args}));
    }
    expect(results[1]).toEqual(results[0]);
  });
});
`;
}

/**
 * The response body before and after the change: the fields the code reads under their old names
 * (with renamed enum fields set to an old value), then under their new names and values.
 */
function renamePair(site: LockedCallSite, fix: Fix): { before: unknown; after: unknown } {
  const paths = site.surface.fields;
  // A rename given as a bare name ("folderId") applies wherever that field appears; a path applies at that path.
  const rename = (p: string) => {
    for (const { from, to } of fix.fields ?? []) {
      if (!/[.[]/.test(from)) {
        const segs = p.split(".");
        const i = segs.findIndex((seg) => seg.replace(/\[\]/g, "") === from);
        if (i >= 0) return [...segs.slice(0, i), segs[i]!.replace(from, to), ...segs.slice(i + 1)].join(".");
      } else if (p === from || p.startsWith(`${from}.`) || p.startsWith(`${from}[]`)) return to + p.slice(from.length);
    }
    return p;
  };
  const oldValues: Record<string, unknown> = {};
  const newValues: Record<string, unknown> = {};
  for (const { field, values } of fix.enums ?? []) {
    const compared = site.surface.enums.find((e) => e.field === field)?.values ?? [];
    const pick = values.find((v) => compared.includes(v.from)) ?? values[0]!;
    oldValues[field] = pick.from;
    newValues[rename(field)] = pick.to;
  }
  return { before: bodyFromPaths(paths, oldValues), after: bodyFromPaths(paths.map(rename), newValues) };
}

function describeFix(fix: Fix): string {
  const parts: string[] = [];
  if (fix.path) parts.push(`${fix.path.to} instead of ${fix.path.from}`);
  if (fix.query) parts.push(`${fix.query.name}=${fix.query.value}`);
  if (fix.header) parts.push(`${fix.header.name}: ${fix.header.value}`);
  return parts.join(", ");
}

function response(name: string, shape: ResponseShape): string {
  const body = synthesizeBody(shape);
  const headers = shape.headers["content-type"] ? { "content-type": shape.headers["content-type"] } : {};
  return `  { name: ${JSON.stringify(name)}, status: ${shape.status}, headers: ${JSON.stringify(headers)}, body: ${JSON.stringify(body)} }`;
}

/** The exported function (declaration or `export const f = () => …`) enclosing the call. */
function exportedFunction(call: Node): { name: string; params: ParameterDeclaration[] } | undefined {
  for (const anc of call.getAncestors()) {
    if (Node.isFunctionDeclaration(anc) && anc.isExported() && anc.getName()) return { name: anc.getName()!, params: anc.getParameters() };
    if (Node.isArrowFunction(anc) || Node.isFunctionExpression(anc)) {
      const decl = anc.getParent();
      if (Node.isVariableDeclaration(decl) && decl.getVariableStatement()?.isExported()) return { name: decl.getName(), params: anc.getParameters() };
    }
  }
  return undefined;
}

/** A plausible argument for a parameter, from its declared type (same-file interfaces and type literals are expanded). */
function argument(p: ParameterDeclaration, sf: SourceFile): string {
  const type = p.getTypeNode();
  return type ? valueFor(type, p.getName(), sf, 0) : JSON.stringify(`shapi-${p.getName()}`);
}

function valueFor(type: TypeNode, name: string, sf: SourceFile, depth: number): string {
  if (depth > 4) return "undefined as never";
  switch (type.getKind()) {
    case SyntaxKind.StringKeyword:
      return JSON.stringify(`shapi-${name}`);
    case SyntaxKind.NumberKeyword:
      return "1";
    case SyntaxKind.BooleanKeyword:
      return "true";
  }
  if (Node.isTypeLiteral(type)) return objectFrom(type.getProperties(), sf, depth);
  if (Node.isTypeReference(type)) {
    const ref = type.getTypeName().getText();
    const iface = sf.getInterface(ref);
    if (iface) return objectFrom(iface.getProperties(), sf, depth);
    const alias = sf.getTypeAlias(ref)?.getTypeNode();
    if (alias) return valueFor(alias, name, sf, depth + 1);
  }
  if (Node.isArrayTypeNode(type)) return "[]";
  return "undefined as never";
}

function objectFrom(props: { getName(): string; getTypeNode(): TypeNode | undefined; hasQuestionToken(): boolean }[], sf: SourceFile, depth: number): string {
  const entries = props
    .filter((p) => !p.hasQuestionToken())
    .map((p) => {
      const t = p.getTypeNode();
      return `${JSON.stringify(p.getName())}: ${t ? valueFor(t, p.getName(), sf, depth + 1) : "undefined as never"}`;
    });
  return `{ ${entries.join(", ")} }`;
}

function toImport(rel: string): string {
  const noExt = rel.replace(/\.(c|m)?[jt]sx?$/, "");
  return noExt.startsWith(".") ? noExt : `./${noExt}`;
}
