import path from "node:path";
import type { Advisory, Fix, LockedCallSite } from "@shapi/core";
import type { ResponseShape } from "@shapi/shapes";
import { Node, Project, ScriptKind, SyntaxKind, type ParameterDeclaration, type SourceFile, type TypeNode } from "ts-morph";
import { findCall } from "./recipe";
import { bodyFromPaths, synthesizeBody } from "./synth";

export interface ContractTestInput {
  callSite: LockedCallSite;
  advisory: Advisory;
  /**
   * The response the code was written against, and the one the provider sends now. Not needed when
   * the advisory has a `fix`: the test is then built from the fix and the fields the code reads.
   */
  before?: ResponseShape;
  after?: ResponseShape;
  /** Current text of the call site's file. */
  sourceText: string;
  /** Where to write the test (repo-relative); default test/shapi/<advisory id>.test.ts. */
  file?: string;
}

export type ContractTest =
  | {
      status: "generated";
      file: string;
      content: string;
      functionName: string;
      /** What the test checks: the request the code sends, the same result for renamed fields, or that the recorded responses are handled. */
      kind: "request" | "same-result" | "recorded";
    }
  | { status: "unsupported"; reason: string };

/** Where generated tests go, relative to the repo root. */
export const CONTRACT_DIR = "test/shapi";

/**
 * Marks the failure a generated test reports when the code breaks the way the advisory says it will.
 * A baseline run that fails without it failed for another reason (the generated arguments, the
 * environment, an import) and proves nothing about the change.
 */
export const BREAKAGE = "SHAPI breakage";
/** Marks a generated test that cannot check this function at all (for example it returns nothing to compare). */
export const UNTESTABLE = "SHAPI cannot test this";

/** Status the stubbed provider answers a retired request with. */
const RETIRED_STATUS = 410;

/**
 * Generate a vitest file that calls the function containing the call site, with the HTTP client it
 * uses replaced by a fake that answers through one `respond()` function: global fetch (and node-fetch,
 * ky), axios, got, or the SDK package. What `respond()` answers depends on the change:
 * - a request change (the advisory's `fix` has a path, query or header): the provider rejects the
 *   retired request, so the test fails until the code sends the new one and still works;
 * - a response rename (`fix` has fields or enums): the function must return the same result for the
 *   old and the new response;
 * - otherwise the recorded before and after responses: the function must handle both.
 */
export function generateContractTest(input: ContractTestInput): ContractTest {
  const { callSite, advisory, before, after } = input;
  const fix = advisory.fix;

  const project = new Project({ useInMemoryFileSystem: true, skipFileDependencyResolution: true, compilerOptions: { allowJs: true } });
  const sf = project.createSourceFile(`/${callSite.file}`, input.sourceText, {
    scriptKind: /\.(c|m)?jsx?$/.test(callSite.file) ? ScriptKind.JS : ScriptKind.TS,
  });
  const call = findCall(sf, callSite);
  if (!call) return { status: "unsupported", reason: `no call at ${callSite.file}:${callSite.line}:${callSite.column}` };

  const transport = transportFor(callSite, sf);
  if ("reason" in transport) return { status: "unsupported", reason: transport.reason };

  const fn = exportedFunction(call, sf);
  if (!fn) return { status: "unsupported", reason: "the call site is not inside an exported function" };

  const file = input.file ?? `${CONTRACT_DIR}/${advisory.id}.test.ts`;
  const importPath = toImport(path.posix.relative(path.posix.dirname(file), callSite.file));
  const parts: TestParts = {
    header: `// Generated by SHAPI for advisory ${advisory.id}: ${oneLine(advisory.title)}
// Call site: ${oneLine(`${callSite.file}:${callSite.line} (${callSite.method} ${callSite.endpoint}, via ${callSite.client})`)}`,
    fn: fn.name,
    importName: fn.importName,
    importPath,
    args: fn.params.map((p) => argument(p, sf)).join(", "),
    advisory,
    transport,
  };

  if (fix && (fix.path || fix.query || fix.header)) {
    if (callSite.kind === "sdk") return { status: "unsupported", reason: `the fix changes the request, which ${callSite.client} builds itself` };
    return { status: "generated", file, content: requestTest({ ...parts, fix, body: renamePair(callSite, fix).after }), functionName: fn.name, kind: "request" };
  }
  if (fix && (fix.fields || fix.enums)) {
    return { status: "generated", file, content: sameResultTest({ ...parts, ...renamePair(callSite, fix) }), functionName: fn.name, kind: "same-result" };
  }
  if (!before || !after) return { status: "unsupported", reason: "no before/after responses for this endpoint, and the advisory has no fix to build a test from" };
  try {
    return { status: "generated", file, content: recordedTest({ ...parts, before, after }), functionName: fn.name, kind: "recorded" };
  } catch (err) {
    return { status: "unsupported", reason: err instanceof Error ? err.message : String(err) };
  }
}

interface Transport {
  /** `vi.mock(...)` for the client package, or "" when stubbing global fetch is enough. */
  mock: string;
  /** Stub global fetch in each test (fetch, node-fetch, ky, and SDKs that call fetch). */
  stubFetch: boolean;
  /** Words for the test's comment, for example "axios". */
  name: string;
}

interface TestParts {
  header: string;
  /** The function's name in the test. */
  fn: string;
  /** The name the module exports it under ("default" for a default export). */
  importName: string;
  importPath: string;
  args: string;
  advisory: Advisory;
  transport: Transport;
}

/** The fake for the call site's client: how the generated test intercepts its requests. */
function transportFor(site: LockedCallSite, sf: SourceFile): Transport | { reason: string } {
  if (site.kind === "http") {
    if (site.client === "fetch" || site.client === "ky") return { mock: "", stubFetch: true, name: "fetch" };
    if (site.client === "node-fetch") {
      return { mock: `vi.mock("node-fetch", () => ({ default: (input: RequestInfo | URL, init?: RequestInit) => globalThis.fetch(input, init) }));\n`, stubFetch: true, name: "node-fetch" };
    }
    if (site.client === "axios") return { mock: AXIOS_FAKE, stubFetch: false, name: "axios" };
    if (site.client === "got") return { mock: GOT_FAKE, stubFetch: false, name: "got" };
    return { reason: `contract tests support fetch, node-fetch, ky, axios, got and SDK call sites; this one uses ${site.client}` };
  }
  // SDK: every method chain on the client resolves to this call site's endpoint.
  const decl = sf.getImportDeclarations().find((d) => d.getModuleSpecifierValue() === site.client);
  if (!decl) return { reason: `${site.file} does not import ${site.client} with an import statement` };
  const names = decl.getNamedImports().map((n) => n.getName());
  const exports = [`default: client`, ...names.map((n) => `${JSON.stringify(n)}: client`)].join(", ");
  const url = `https://${site.host ?? "sdk.invalid"}${site.endpoint ?? "/"}`;
  // Octokit answers { status, data, headers } like axios; other SDKs return the parsed body.
  const envelope = site.provider === "github" ? `{ status: res.status, data: res.body, headers: res.headers }` : `res.body`;
  return {
    mock: `vi.mock(${JSON.stringify(site.client)}, () => {
  const call = async () => {
    const res = shapi.respond({ method: ${JSON.stringify(site.method ?? "GET")}, url: ${JSON.stringify(url)}, headers: {} });
    if (res.status >= 400) throw Object.assign(new Error(\`${site.client} request failed with \${res.status}\`), { status: res.status, statusCode: res.status, response: { status: res.status, data: res.body } });
    return ${envelope};
  };
  const client: any = new Proxy(function () {}, {
    get: (_t, prop) => (prop === "then" || typeof prop === "symbol" ? undefined : client),
    apply: () => call(),
    construct: () => client,
  });
  return { ${exports} };
});
`,
    stubFetch: false,
    name: `a fake ${site.client} client`,
  };
}

/** Shared by every generated test: the request the code sent, and the hook that answers it. */
function preamble(p: TestParts): string {
  return `import { afterEach, describe, expect, it, vi } from "vitest";

type ShapiRequest = { method: string; url: string; headers: Record<string, string> };
type ShapiResponse = { status: number; body: unknown; headers: Record<string, string> };
const shapi = vi.hoisted(() => ({
  respond: (_req: { method: string; url: string; headers: Record<string, string> }): { status: number; body: unknown; headers: Record<string, string> } => ({ status: 200, body: null, headers: {} }),
  lower: (h: unknown): Record<string, string> =>
    Object.fromEntries(Object.entries((h ?? {}) as Record<string, unknown>).filter(([, v]) => v !== undefined).map(([k, v]) => [k.toLowerCase(), String(v)])),
}));
${p.transport.mock}
${p.importName === "default" ? `import ${p.fn}` : `import { ${p.fn} }`} from "${p.importPath}";
${
  p.transport.stubFetch
    ? `
const shapiFetch = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
  const url = typeof input === "string" ? input : input instanceof URL ? input.href : input.url;
  // forEach rather than entries(): it type-checks without the "dom.iterable" lib.
  const headers: Record<string, string> = {};
  new Headers(init?.headers ?? (input instanceof Request ? input.headers : undefined)).forEach((value, name) => {
    headers[name] = value;
  });
  const res = shapi.respond({ method: (init?.method ?? (input instanceof Request ? input.method : "GET")).toUpperCase(), url, headers });
  return new Response(res.body === null ? null : JSON.stringify(res.body), { status: res.status, headers: res.headers });
});
`
    : ""
}
afterEach(() => {
  vi.unstubAllGlobals();
});

async function run(respond: (req: ShapiRequest) => ShapiResponse): Promise<unknown> {
  shapi.respond = respond;${p.transport.stubFetch ? `\n  vi.stubGlobal("fetch", shapiFetch);` : ""}
  return ${p.fn}(${p.args});
}

/** Marks a failure as the API change itself, as opposed to anything else going wrong in the test. */
function breakage(err: unknown, what: string): unknown {
  if (!(err instanceof Error)) return new Error(\`${BREAKAGE}: \${what}: \${String(err)}\`);
  err.message = \`${BREAKAGE}: \${what}: \${err.message}\`;
  return err;
}
`;
}

const JSON_HEADERS = `{ "content-type": "application/json" }`;

/** The provider answers the retired request with 410 and anything else with a body holding the fields the code reads. */
function requestTest(p: TestParts & { fix: Fix; body: unknown }): string {
  const checks: string[] = [];
  if (p.fix.path) checks.push(`url.href.includes(${JSON.stringify(p.fix.path.from)})`);
  if (p.fix.query) {
    const name = JSON.stringify(p.fix.query.name);
    const below = p.advisory.trigger.query?.find((q) => q.name === p.fix.query!.name)?.below;
    checks.push(
      below === undefined
        ? `(url.searchParams.has(${name}) && url.searchParams.get(${name}) !== ${JSON.stringify(p.fix.query.value)})`
        : `(url.searchParams.has(${name}) && Number(url.searchParams.get(${name})) < ${below})`,
    );
  }
  if (p.fix.header) {
    const name = JSON.stringify(p.fix.header.name.toLowerCase());
    checks.push(`(${name} in req.headers && req.headers[${name}] !== ${JSON.stringify(p.fix.header.value)})`);
  }
  return `${p.header}
// The provider no longer accepts the old request: ${p.transport.name} is replaced by a stub that answers it
// with ${RETIRED_STATUS}, and answers anything else with a body holding the fields the code reads. The test
// fails until ${p.fn}() sends the new request (${describeFix(p.fix)}) and still works.
${preamble(p)}
const body = ${JSON.stringify(p.body)};

function retired(req: ShapiRequest): boolean {
  const url = new URL(req.url, "https://shapi.invalid");
  return ${checks.join(" || ")};
}

describe("SHAPI contract: ${p.advisory.id}", () => {
  it("${p.fn} sends the new request and handles the response", async () => {
    const sent: boolean[] = [];
    let error: unknown;
    await run((req) => {
      const old = retired(req);
      sent.push(old);
      return old ? { status: ${RETIRED_STATUS}, body: { error: "retired request (SHAPI contract test)" }, headers: ${JSON_HEADERS} } : { status: 200, body, headers: ${JSON_HEADERS} };
    }).catch((err: unknown) => {
      error = err;
    });
    // Failing before any request is not the API change: the arguments or the environment are off.
    if (sent.length === 0) throw error ?? new Error("${p.fn}() sent no request");
    if (sent.includes(true)) throw breakage(error ?? new Error("the provider no longer accepts it"), "${p.fn}() sent the retired request");
    if (error) throw error;
  });
});
`;
}

/** The function must return the same result whether the provider uses the old or the new field names and values. */
function sameResultTest(p: TestParts & { before: unknown; after: unknown }): string {
  return `${p.header}
// The provider renamed fields or enum values. This test calls ${p.fn}() once with the old response and
// once with the new one (${p.transport.name} replaced by a stub), and expects the same result: it fails
// while the code only reads the old names.
${preamble(p)}
const responses = [
  { name: "old", body: ${JSON.stringify(p.before)} },
  { name: "new", body: ${JSON.stringify(p.after)} },
];

describe("SHAPI contract: ${p.advisory.id}", () => {
  it("${p.fn} returns the same result for the old and the new response", async () => {
    const answer = (body: unknown) => () => ({ status: 200, body, headers: ${JSON_HEADERS} });
    const old = await run(answer(responses[0]!.body));
    if (old === undefined) throw new Error("${UNTESTABLE}: ${p.fn}() returns nothing, so there is no result to compare");
    let now: unknown;
    try {
      now = await run(answer(responses[1]!.body));
    } catch (err) {
      throw breakage(err, "${p.fn}() fails on the new response");
    }
    try {
      expect(now).toEqual(old);
    } catch (err) {
      throw breakage(err, "${p.fn}() returns something else for the new response");
    }
  });
});
`;
}

/** The recorded response the code was written for and the one the provider sends now: the function must handle both. */
function recordedTest(p: TestParts & { before: ResponseShape; after: ResponseShape }): string {
  const responses = [response(`before (${p.before.status})`, p.before), response(`after (${p.after.status})`, p.after)].join(",\n");
  return `${p.header}
// Calls ${p.fn}() with ${p.transport.name} returning the response the code was written for and the one
// ${p.advisory.provider} sends now. It fails while the code accepts only the old response.
${preamble(p)}
const responses: { name: string; status: number; headers: Record<string, string>; body: unknown }[] = [
${responses},
];

// Only a failure on the new response, with the old one handled, is the API change.
let oldHandled = false;

describe("SHAPI contract: ${p.advisory.id}", () => {
  for (const [i, r] of responses.entries()) {
    it(\`${p.fn} handles the \${r.name} response\`, async () => {
      const seen: ShapiRequest[] = [];
      try {
        await run((req) => (seen.push(req), { status: r.status, body: r.body, headers: r.headers }));
      } catch (err) {
        throw i === 1 && oldHandled && seen.length > 0 ? breakage(err, "${p.fn}() fails on the response ${p.advisory.provider} sends now") : err;
      }
      expect(seen.length).toBeGreaterThan(0);
      if (i === 0) oldHandled = true;
    });
  }
});
`;
}

/**
 * The response body before and after the change: the fields the code reads under their old names
 * (with renamed enum fields set to an old value), then under their new names and values.
 */
function renamePair(site: LockedCallSite, fix: Fix): { before: unknown; after: unknown } {
  const paths = site.surface.fields;
  // A rename given as a bare name ("folderId") applies wherever that field appears; a path applies at that path.
  // Every matching rename applies, in order: a renamed parent and a renamed leaf both change the path.
  const rename = (p: string) => {
    for (const { from, to } of fix.fields ?? []) {
      if (!/[.[]/.test(from)) {
        const segs = p.split(".");
        const i = segs.findIndex((seg) => seg.replace(/\[\]/g, "") === from);
        if (i >= 0) p = [...segs.slice(0, i), segs[i]!.replace(from, to), ...segs.slice(i + 1)].join(".");
      } else if (p === from || p.startsWith(`${from}.`) || p.startsWith(`${from}[]`)) p = to + p.slice(from.length);
    }
    return p;
  };
  const oldValues: Record<string, unknown> = {};
  const newValues: Record<string, unknown> = {};
  for (const { field, values } of fix.enums ?? []) {
    const compared = site.surface.enums.find((e) => e.field === field)?.values ?? [];
    const pick = values.find((v) => compared.includes(v.from)) ?? values[0]!;
    oldValues[field] = pick.from;
    newValues[rename(field)] = pick.to;
  }
  return { before: bodyFromPaths(paths, oldValues), after: bodyFromPaths(paths.map(rename), newValues) };
}

function describeFix(fix: Fix): string {
  const parts: string[] = [];
  if (fix.path) parts.push(`${fix.path.to} instead of ${fix.path.from}`);
  if (fix.query) parts.push(`${fix.query.name}=${fix.query.value}`);
  if (fix.header) parts.push(`${fix.header.name}: ${fix.header.value}`);
  return parts.join(", ");
}

