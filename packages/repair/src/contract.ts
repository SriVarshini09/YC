import path from "node:path";
import type { Advisory, LockedCallSite } from "@shapi/core";
import type { ResponseShape } from "@shapi/shapes";
import { Node, Project, ScriptKind, SyntaxKind, type ParameterDeclaration, type SourceFile, type TypeNode } from "ts-morph";
import { findCall } from "./recipe";
import { synthesizeBody } from "./synth";

export interface ContractTestInput {
  callSite: LockedCallSite;
  advisory: Advisory;
  /** The response the code was written against, and the one the provider sends now. */
  before: ResponseShape;
  after: ResponseShape;
  /** Current text of the call site's file. */
  sourceText: string;
}

export type ContractTest =
  | { status: "generated"; file: string; content: string; functionName: string }
  | { status: "unsupported"; reason: string };

/** Where generated tests go, relative to the repo root. */
export const CONTRACT_DIR = "test/shapi";

/**
 * Generate a vitest file that calls the function containing the call site with
 * `fetch` stubbed to return the before and the after response. It fails while
 * the code only handles the old response and passes once it handles both.
 */
export function generateContractTest(input: ContractTestInput): ContractTest {
  const { callSite, advisory, before, after } = input;
  if (callSite.kind !== "http" || callSite.client !== "fetch") {
    return { status: "unsupported", reason: `contract tests support global fetch call sites; this one uses ${callSite.client}` };
  }

  const project = new Project({ useInMemoryFileSystem: true, skipFileDependencyResolution: true, compilerOptions: { allowJs: true } });
  const sf = project.createSourceFile(`/${callSite.file}`, input.sourceText, {
    scriptKind: /\.(c|m)?jsx?$/.test(callSite.file) ? ScriptKind.JS : ScriptKind.TS,
  });
  const call = findCall(sf, callSite);
  if (!call) return { status: "unsupported", reason: `no call at ${callSite.file}:${callSite.line}:${callSite.column}` };

  const fn = exportedFunction(call);
  if (!fn) return { status: "unsupported", reason: "the call site is not inside an exported function" };

  let responses: string;
  try {
    responses = [response(`before (${before.status})`, before), response(`after (${after.status})`, after)].join(",\n");
  } catch (err) {
    return { status: "unsupported", reason: err instanceof Error ? err.message : String(err) };
  }

  const file = `${CONTRACT_DIR}/${advisory.id}.test.ts`;
  const importPath = toImport(path.posix.relative(path.posix.dirname(file), callSite.file));
  const args = fn.params.map((p) => argument(p, sf)).join(", ");
  const content = `// Generated by SHAPI for advisory ${advisory.id}: ${advisory.title}
// Call site: ${callSite.file}:${callSite.line} (${callSite.method} ${callSite.endpoint})
// Calls ${fn.name}() with fetch returning the response the code was written for and the one
// ${advisory.provider} sends now. It fails while the code accepts only the old response.
import { afterEach, describe, expect, it, vi } from "vitest";
import { ${fn.name} } from "${importPath}";

const responses = [
${responses},
];

describe("SHAPI contract: ${advisory.id}", () => {
  afterEach(() => {
    vi.unstubAllGlobals();
  });

  for (const r of responses) {
    it(\`${fn.name} handles the \${r.name} response\`, async () => {
      const fetchMock = vi.fn(async () => new Response(r.body === null ? null : JSON.stringify(r.body), { status: r.status, headers: r.headers }));
      vi.stubGlobal("fetch", fetchMock);
      await ${fn.name}(${args});
      expect(fetchMock).toHaveBeenCalled();
    });
  }
});
`;
  return { status: "generated", file, content, functionName: fn.name };
}

function response(name: string, shape: ResponseShape): string {
  const body = synthesizeBody(shape);
  const headers = shape.headers["content-type"] ? { "content-type": shape.headers["content-type"] } : {};
  return `  { name: ${JSON.stringify(name)}, status: ${shape.status}, headers: ${JSON.stringify(headers)}, body: ${JSON.stringify(body)} }`;
}

/** The exported function (declaration or `export const f = () => …`) enclosing the call. */
function exportedFunction(call: Node): { name: string; params: ParameterDeclaration[] } | undefined {
  for (const anc of call.getAncestors()) {
    if (Node.isFunctionDeclaration(anc) && anc.isExported() && anc.getName()) return { name: anc.getName()!, params: anc.getParameters() };
    if (Node.isArrowFunction(anc) || Node.isFunctionExpression(anc)) {
      const decl = anc.getParent();
      if (Node.isVariableDeclaration(decl) && decl.getVariableStatement()?.isExported()) return { name: decl.getName(), params: anc.getParameters() };
    }
  }
  return undefined;
}

/** A plausible argument for a parameter, from its declared type (same-file interfaces and type literals are expanded). */
function argument(p: ParameterDeclaration, sf: SourceFile): string {
  const type = p.getTypeNode();
  return type ? valueFor(type, p.getName(), sf, 0) : JSON.stringify(`shapi-${p.getName()}`);
}

function valueFor(type: TypeNode, name: string, sf: SourceFile, depth: number): string {
  if (depth > 4) return "undefined as never";
  switch (type.getKind()) {
    case SyntaxKind.StringKeyword:
      return JSON.stringify(`shapi-${name}`);
    case SyntaxKind.NumberKeyword:
      return "1";
    case SyntaxKind.BooleanKeyword:
      return "true";
  }
  if (Node.isTypeLiteral(type)) return objectFrom(type.getProperties(), sf, depth);
  if (Node.isTypeReference(type)) {
    const ref = type.getTypeName().getText();
    const iface = sf.getInterface(ref);
    if (iface) return objectFrom(iface.getProperties(), sf, depth);
    const alias = sf.getTypeAlias(ref)?.getTypeNode();
    if (alias) return valueFor(alias, name, sf, depth + 1);
  }
  if (Node.isArrayTypeNode(type)) return "[]";
  return "undefined as never";
}

function objectFrom(props: { getName(): string; getTypeNode(): TypeNode | undefined; hasQuestionToken(): boolean }[], sf: SourceFile, depth: number): string {
  const entries = props
    .filter((p) => !p.hasQuestionToken())
    .map((p) => {
      const t = p.getTypeNode();
      return `${JSON.stringify(p.getName())}: ${t ? valueFor(t, p.getName(), sf, depth + 1) : "undefined as never"}`;
    });
  return `{ ${entries.join(", ")} }`;
}

function toImport(rel: string): string {
  const noExt = rel.replace(/\.(c|m)?[jt]sx?$/, "");
  return noExt.startsWith(".") ? noExt : `./${noExt}`;
}
