const surface = (over: Partial<CallSite["surface"]> = {}): CallSite["surface"] => ({ fields: [], statusCodes: [], checksOk: false, enums: [], headers: [], query: [], responseHeaders: [], ...over });
const site = (file: string, line: number, provider: string, method: CallSite["method"], host: string, endpoint: string, over: Partial<CallSite> = {}): CallSite => ({
  file,
  line,
  column: 11,
  provider,
  kind: "http",
  client: "fetch",
  method,
  host,
  endpoint,
  resolved: true,
  surface: surface(),
  ...over,
});

interface Seed {
  full_name: string;
  private: boolean;
  paused?: boolean;
  sites: CallSite[];
  declared: { provider: string; package: string }[];
  findings: { file: string; line: number; advisory: string; kind: "affected" | "exposed"; reasons: string[]; at?: Date }[];
  prs: { advisory: string; number: number; state: "open" | "closed" | "merged"; at: Date; closed?: Date; repair?: FixRepair; stopped?: boolean }[];
  scans: { sha: string; status: "succeeded" | "failed"; at: Date; error?: string; lock?: boolean }[];
}

const advisoriesById = new Map(loadAdvisories(path.join(root, "advisories")).map((a) => [a.id, a]));
const adv = (id: string) => {
  const a = advisoriesById.get(id);
  if (!a) throw new Error(`no advisory ${id}`);
  return a;
};

/** A verified fix as the fix job records it: the diff and the contract test red, then green. */
function repairFor(advisoryId: string, file: string, line: number, before: string, after: string, method: CallSite["method"], endpoint: string, sandbox = "e2b:sbx_8f21c"): FixRepair {
  const test = `test/shapi/${advisoryId}.test.ts`;
  const testBody = `import { afterEach, describe, expect, it, vi } from "vitest";\n\n// Generated by SHAPI from advisory ${advisoryId}: the request the code sends, answered as the provider does now.\ndescribe("SHAPI contract: ${advisoryId}", () => {\n  afterEach(() => vi.restoreAllMocks());\n  it("handles the response the provider sends now", async () => {\n    // ...\n  });\n});\n`;
  return summarizeRepair(
    {
      advisory: adv(advisoryId),
      sites: [
        {
          callSite: { file, line, method, endpoint },
          result: {
            status: "fixed",
            method: "recipe",
            sandbox,
            changes: [],
            test: { file: test, content: testBody },
            baseline: { passed: false, exitCode: 1, output: ` FAIL  ${test} > SHAPI contract: ${advisoryId} > handles the response the provider sends now\nAssertionError: expected [Function] to not throw an error but 'Error: unexpected response' was thrown\n\n Test Files  1 failed (1)\n      Tests  1 failed (1)\n   Duration  412ms\n` },
            attempts: [{ method: "recipe", outcome: "passed", detail: adv(advisoryId).recipeId ?? "recipe", run: { passed: true, exitCode: 0, output: ` ✓ ${test} (1 test) 9ms\n\n Test Files  1 passed (1)\n      Tests  1 passed (1)\n   Duration  388ms\n` } }],
          },
        },
      ],
      changes: [
        { file, before, after, notes: [] },
        { file: test, before: "", after: testBody, notes: [] },
      ],
      method: "recipe",
      sandbox,
    },
    hours(6),
  );
}

