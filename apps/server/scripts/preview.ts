async function seed(db: Db) {
  const account = await db
    .insertInto("accounts")
    .values({ github_installation_id: 999001, login: "acme", type: "Organization", settings: JSON.stringify({ prLimits: { hourly: 2, open: 10 }, failOnAffected: false, llmFixes: false, slackWebhookUrl: "https://hooks.slack.com/services/T000/B000/previewXYZ123" }) })
    .returning("id")
    .executeTakeFirstOrThrow();
  await db.insertInto("billing").values({ account_id: account.id, stripe_customer_id: "cus_preview", stripe_subscription_id: "sub_preview", status: "active", quantity: 3, current_period_end: new Date(Date.now() + 19 * 86_400_000), updated_at: new Date() }).execute();
  let repoId = 4100;
  for (const s of seeds) {
    const repo = await db
      .insertInto("repositories")
      .values({ account_id: account.id, github_repo_id: repoId++, full_name: s.full_name, default_branch: "main", private: s.private, dashboard_issue: 1, settings: JSON.stringify(s.paused ? { paused: true } : {}), last_scan_sha: s.scans.at(-1)!.sha, last_scanned_at: s.scans.at(-1)!.at })
      .returning("id")
      .executeTakeFirstOrThrow();
    const lock = createApiLock({ callSites: s.sites, declared: s.declared }, "shapi preview");
    let lockScan: string | undefined;
    for (const scan of s.scans) {
      const row = await db
        .insertInto("scans")
        .values({
          account_id: account.id,
          repository_id: repo.id,
          sha: scan.sha,
          status: scan.status,
          api_lock: scan.status === "succeeded" ? JSON.stringify(lock) : null,
          error: scan.error ?? null,
          created_at: new Date(scan.at.getTime() - 90_000),
          started_at: new Date(scan.at.getTime() - 80_000),
          finished_at: scan.at,
        })
        .returning("id")
        .executeTakeFirstOrThrow();
      if (scan.status === "succeeded") lockScan = row.id;
    }
    for (const f of s.findings) {
      const callSite = lock.callSites.find((c) => c.file === f.file && c.line === f.line)!;
      await db.insertInto("findings").values({ account_id: account.id, repository_id: repo.id, scan_id: lockScan!, advisory_id: f.advisory, kind: f.kind, call_site: JSON.stringify(callSite), reasons: JSON.stringify(f.reasons), created_at: f.at ?? new Date() }).execute();
    }
    for (const p of s.prs) {
      await db
        .insertInto("fix_prs")
        .values({
          account_id: account.id,
          repository_id: repo.id,
          advisory_id: p.advisory,
          branch: `shapi/${p.advisory}`,
          number: p.number,
          url: `https://github.com/${s.full_name}/pull/${p.number}`,
          state: p.state,
          stopped: p.stopped ?? false,
          head_sha: "b".repeat(40),
          created_at: p.at,
          updated_at: p.closed ?? p.at,
          closed_at: p.closed ?? null,
          repair: p.repair ? JSON.stringify(p.repair) : null,
        })
        .execute();
    }
  }
  return account.id;
}

